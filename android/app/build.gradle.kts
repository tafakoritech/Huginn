// The Android client talks ONLY to the real Huginn HTTP API. There is no
// mock/demo backend in any runtime build variant (see app/src/test for the
// test-only mock). Base URL is overridable at build time, e.g.:
//   ./gradlew :app:assembleDebug -PHUGINN_API_BASE_URL=https://huginn.example.com/
// Defaults to the Android emulator's host loopback (10.0.2.2) which reaches
// the host machine's Huginn API on port 8080. Physical devices must pass a
// host/LAN-reachable address via HUGINN_API_BASE_URL.
val apiBaseUrl: String = providers.gradleProperty("HUGINN_API_BASE_URL")
    .getOrElse("http://192.168.1.200:8080/")

